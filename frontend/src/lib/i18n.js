export function translate(lang, key, params) {
  const dict = dictionaries[lang] || dictionaries.en;
  let str = dict[key] ?? dictionaries.en[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      str = str.replace(`{${name}}`, value);
    }
  }
  return str;
}

